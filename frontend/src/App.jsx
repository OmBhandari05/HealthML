import { useState } from 'react'
import './App.css'

const initialDiabetesForm = {
  high_bp: '', high_chol: '', chol_check: '1', bmi: '', smoker: '', stroke: '',
  heart_disease_or_attack: '', physical_activity: '', fruits: '', veggies: '',
  heavy_alcohol_consumption: '', any_healthcare: '', no_doc_bc_cost: '',
  general_health: '', mental_health_days: '', physical_health_days: '',
  difficulty_walking: '', sex: '', age_category: '', education: '', income: '',
}

const initialCardiovascularForm = {
  age: '', sex: '', cp: '', trestbps: '', chol: '', fbs: '', restecg: '',
  thalach: '', exang: '', oldpeak: '', slope: '', ca: '', thal: '',
}

const API_BASE = 'http://127.0.0.1:8000/api/v1'

function App() {
  const [page, setPage] = useState('home')
  const [disease, setDisease] = useState('diabetes')
  const [diabetesForm, setDiabetesForm] = useState(initialDiabetesForm)
  const [cardioForm, setCardioForm] = useState(initialCardiovascularForm)
  const [result, setResult] = useState(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')

  const activeForm = disease === 'diabetes' ? diabetesForm : cardioForm
  const setActiveForm = disease === 'diabetes' ? setDiabetesForm : setCardioForm

  const updateField = (field, value) => {
    setActiveForm((current) => ({ ...current, [field]: value }))
  }

  const scrollTop = () => window.scrollTo({ top: 0, behavior: 'smooth' })
  const goHome = () => { setPage('home'); setError(''); scrollTop() }
  const openAssessment = (selectedDisease) => {
    setDisease(selectedDisease)
    setResult(null)
    setError('')
    setPage('assessment')
    scrollTop()
  }

  const handleSubmit = async (event) => {
    event.preventDefault()
    setLoading(true)
    setError('')
    setResult(null)

    let payload
    let endpoint
    if (disease === 'diabetes') {
      payload = Object.fromEntries(
        Object.entries(diabetesForm).map(([key, value]) => [key, Number(value)])
      )
      endpoint = `${API_BASE}/predict/diabetes`
    } else {
      payload = {
        age: Number(cardioForm.age),
        sex: Number(cardioForm.sex),
        cp: Number(cardioForm.cp),
        trestbps: Number(cardioForm.trestbps),
        chol: Number(cardioForm.chol),
        fbs: Number(cardioForm.fbs),
        restecg: Number(cardioForm.restecg),
        thalach: Number(cardioForm.thalach),
        exang: Number(cardioForm.exang),
        oldpeak: Number(cardioForm.oldpeak),
        slope: Number(cardioForm.slope),
        ca: cardioForm.ca === '' ? null : Number(cardioForm.ca),
        thal: cardioForm.thal === '' ? null : Number(cardioForm.thal),
      }
      endpoint = `${API_BASE}/predict/cardiovascular`
    }

    try {
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      })
      const data = await response.json().catch(() => ({}))
      if (!response.ok) {
        const detail = Array.isArray(data.detail)
          ? data.detail.map((item) => `${item.loc?.join('.')}: ${item.msg}`).join('; ')
          : data.detail
        throw new Error(detail || `Prediction failed (${response.status}).`)
      }
      setResult(data)
      setPage('result')
      scrollTop()
    } catch (err) {
      setError(err.message || `Unable to connect to the ${disease} API.`)
    } finally {
      setLoading(false)
    }
  }

  const resetAssessment = () => {
    if (disease === 'diabetes') setDiabetesForm(initialDiabetesForm)
    else setCardioForm(initialCardiovascularForm)
    setResult(null)
    setError('')
    setPage('assessment')
    scrollTop()
  }

  if (page === 'result' && result) {
    const percentage = (result.risk_probability * 100).toFixed(1)
    const diseaseLabel = result.disease === 'cardiovascular' ? 'Cardiovascular' : 'Diabetes'
    const threshold = result.disease === 'cardiovascular' ? '60%' : '65%'
    return (
      <div className="app">
        <Navbar goHome={goHome} />
        <main className="result-page">
          <button className="back-button" onClick={() => { setPage('assessment'); setResult(null); scrollTop() }}>← Back to assessment</button>
          <div className="result-header">
            <span className="section-label">{diseaseLabel.toUpperCase()} MODEL ASSESSMENT</span>
            <h1>Your assessment is ready.</h1>
            <p>The result below was generated by the trained {diseaseLabel.toLowerCase()} machine learning model.</p>
          </div>
          <section className="result-card">
            <div className="result-score">
              <span>MODEL SCORE</span>
              <strong>{percentage}%</strong>
              <div className="score-bar"><div className="score-bar-fill" style={{ width: `${Math.min(Number(percentage), 100)}%` }} /></div>
            </div>
            <div className="result-assessment">
              <span>MODEL ASSESSMENT</span>
              <h2>{result.risk_level}</h2>
              <p>This classification uses the model's selected decision threshold. This score is not a medically calibrated probability.</p>
            </div>
          </section>
          <section className="explanation-card">
            <div><span className="section-label">HIGHLIGHTED FACTORS</span><h2>Input observations</h2></div>
            <div className="explanation-list">
              {(result.explanation || []).map((reason, index) => <div className="explanation-item" key={`${index}-${reason}`}><span>•</span><p>{reason}</p></div>)}
            </div>
          </section>
          <section className="result-meta">
            <div><span>MODEL VERSION</span><strong>{result.model_version}</strong></div>
            <div><span>DECISION THRESHOLD</span><strong>{threshold}</strong></div>
            <div><span>ASSESSMENT TYPE</span><strong>Educational ML</strong></div>
          </section>
          <div className="result-disclaimer"><strong>Important</strong><p>{result.disclaimer}</p></div>
          <div className="result-actions">
            <button className="primary-button" onClick={resetAssessment}>New Assessment →</button>
            <button className="secondary-button" onClick={goHome}>Back to Dashboard</button>
          </div>
        </main>
        <Footer />
      </div>
    )
  }

  if (page === 'assessment') {
    const title = disease === 'diabetes' ? 'Diabetes' : 'Cardiovascular'
    return (
      <div className="app">
        <Navbar goHome={goHome} />
        <main className="assessment-page">
          <div className="assessment-header">
            <button className="back-button" onClick={goHome}>← Back to dashboard</button>
            <span className="section-label">{title.toUpperCase()} RISK ASSESSMENT</span>
            <h1>Tell us about your health.</h1>
            <p>Complete the fields below. Your responses will be analyzed by the trained {title.toLowerCase()} model.</p>
            <div className="assessment-note"><strong>Educational assessment</strong><span>This prototype is for research and learning only. It is not a medical diagnosis or a validated clinical risk calculator.</span></div>
          </div>
          <form className="assessment-form" onSubmit={handleSubmit}>
            {disease === 'diabetes' ? (
              <>
                <FormSection number="01" title="Basic information" description="Demographic information used by the original dataset.">
                  <Field label="Age range"><select value={diabetesForm.age_category} onChange={(e) => updateField('age_category', e.target.value)} required><option value="">Select age range</option>{['18–24','25–29','30–34','35–39','40–44','45–49','50–54','55–59','60–64','65–69','70–74','75–79','80+'].map((v,i)=><option value={i+1} key={v}>{v}</option>)}</select></Field>
                  <Field label="Sex (dataset category)"><select value={diabetesForm.sex} onChange={(e) => updateField('sex', e.target.value)} required><option value="">Select</option><option value="0">Female category</option><option value="1">Male category</option></select></Field>
                  <Field label="Education level"><select value={diabetesForm.education} onChange={(e) => updateField('education', e.target.value)} required><option value="">Select</option>{['Never attended school','Elementary school','Some high school','High school graduate','Some college / technical school','College graduate'].map((v,i)=><option value={i+1} key={v}>{v}</option>)}</select></Field>
                  <Field label="Income category"><select value={diabetesForm.income} onChange={(e) => updateField('income', e.target.value)} required><option value="">Select</option>{['Lowest','Low','Lower-middle','Middle','Upper-middle','High','Very high','Highest'].map((v,i)=><option value={i+1} key={v}>{v}</option>)}</select></Field>
                </FormSection>
                <FormSection number="02" title="Health conditions" description="Existing health indicators.">
                  <YesNoField label="Have you been told you have high blood pressure?" value={diabetesForm.high_bp} onChange={(v)=>updateField('high_bp',v)} />
                  <YesNoField label="Have you been told you have high cholesterol?" value={diabetesForm.high_chol} onChange={(v)=>updateField('high_chol',v)} />
                  <YesNoField label="Have you had your cholesterol checked?" value={diabetesForm.chol_check} onChange={(v)=>updateField('chol_check',v)} />
                  <YesNoField label="Have you ever had a stroke?" value={diabetesForm.stroke} onChange={(v)=>updateField('stroke',v)} />
                  <YesNoField label="Have you had coronary heart disease or a heart attack?" value={diabetesForm.heart_disease_or_attack} onChange={(v)=>updateField('heart_disease_or_attack',v)} />
                  <Field label="BMI"><input type="number" min="10" max="98" step="0.1" placeholder="e.g. 27.5" value={diabetesForm.bmi} onChange={(e)=>updateField('bmi',e.target.value)} required /></Field>
                </FormSection>
                <FormSection number="03" title="Lifestyle" description="Lifestyle indicators as encoded in the training dataset.">
                  <YesNoField label="Have you smoked at least 100 cigarettes in your lifetime?" value={diabetesForm.smoker} onChange={(v)=>updateField('smoker',v)} />
                  <YesNoField label="Do you participate in physical activity?" value={diabetesForm.physical_activity} onChange={(v)=>updateField('physical_activity',v)} />
                  <YesNoField label="Do you consume fruit at least once per day?" value={diabetesForm.fruits} onChange={(v)=>updateField('fruits',v)} />
                  <YesNoField label="Do you consume vegetables at least once per day?" value={diabetesForm.veggies} onChange={(v)=>updateField('veggies',v)} />
                  <YesNoField label="Is heavy alcohol consumption recorded for you?" value={diabetesForm.heavy_alcohol_consumption} onChange={(v)=>updateField('heavy_alcohol_consumption',v)} />
                </FormSection>
                <FormSection number="04" title="General health" description="Self-reported health indicators.">
                  <Field label="General health"><select value={diabetesForm.general_health} onChange={(e)=>updateField('general_health',e.target.value)} required><option value="">Select</option><option value="1">Excellent</option><option value="2">Very good</option><option value="3">Good</option><option value="4">Fair</option><option value="5">Poor</option></select></Field>
                  <Field label="Poor mental health days (past 30 days)"><input type="number" min="0" max="30" value={diabetesForm.mental_health_days} onChange={(e)=>updateField('mental_health_days',e.target.value)} required /></Field>
                  <Field label="Poor physical health days (past 30 days)"><input type="number" min="0" max="30" value={diabetesForm.physical_health_days} onChange={(e)=>updateField('physical_health_days',e.target.value)} required /></Field>
                  <YesNoField label="Do you have difficulty walking or climbing stairs?" value={diabetesForm.difficulty_walking} onChange={(v)=>updateField('difficulty_walking',v)} />
                </FormSection>
                <FormSection number="05" title="Healthcare access" description="Healthcare access indicators.">
                  <YesNoField label="Do you have some form of healthcare coverage?" value={diabetesForm.any_healthcare} onChange={(v)=>updateField('any_healthcare',v)} />
                  <YesNoField label="Was there a time you needed a doctor but could not afford it?" value={diabetesForm.no_doc_bc_cost} onChange={(v)=>updateField('no_doc_bc_cost',v)} />
                </FormSection>
              </>
            ) : (
              <>
                <FormSection number="01" title="Basic information" description="Enter the features used by the historical UCI Heart Disease model.">
                  <Field label="Age (years)"><input type="number" min="18" max="100" value={cardioForm.age} onChange={(e)=>updateField('age',e.target.value)} required /></Field>
                  <Field label="Sex category"><select value={cardioForm.sex} onChange={(e)=>updateField('sex',e.target.value)} required><option value="">Select</option><option value="0">Female category (dataset code 0)</option><option value="1">Male category (dataset code 1)</option></select></Field>
                  <Field label="Chest pain type"><select value={cardioForm.cp} onChange={(e)=>updateField('cp',e.target.value)} required><option value="">Select</option><option value="1">Typical angina (1)</option><option value="2">Atypical angina (2)</option><option value="3">Non-anginal pain (3)</option><option value="4">Asymptomatic (4)</option></select></Field>
                  <Field label="Resting blood pressure (mmHg)"><input type="number" min="60" max="260" value={cardioForm.trestbps} onChange={(e)=>updateField('trestbps',e.target.value)} required /></Field>
                  <Field label="Serum cholesterol (mg/dL)"><input type="number" min="50" max="700" value={cardioForm.chol} onChange={(e)=>updateField('chol',e.target.value)} required /></Field>
                </FormSection>
                <FormSection number="02" title="Clinical test features" description="Use values from the dataset's coding definitions or supplied example records; do not guess clinical measurements.">
                  <Field label="Fasting blood sugar over 120 mg/dL"><select value={cardioForm.fbs} onChange={(e)=>updateField('fbs',e.target.value)} required><option value="">Select</option><option value="0">No (0)</option><option value="1">Yes (1)</option></select></Field>
                  <Field label="Resting ECG result"><select value={cardioForm.restecg} onChange={(e)=>updateField('restecg',e.target.value)} required><option value="">Select</option><option value="0">Normal (0)</option><option value="1">ST-T abnormality (1)</option><option value="2">LV hypertrophy (2)</option></select></Field>
                  <Field label="Maximum heart rate achieved"><input type="number" min="50" max="250" value={cardioForm.thalach} onChange={(e)=>updateField('thalach',e.target.value)} required /></Field>
                  <Field label="Exercise-induced angina"><select value={cardioForm.exang} onChange={(e)=>updateField('exang',e.target.value)} required><option value="">Select</option><option value="0">No (0)</option><option value="1">Yes (1)</option></select></Field>
                  <Field label="ST depression (oldpeak)"><input type="number" min="0" max="10" step="0.1" value={cardioForm.oldpeak} onChange={(e)=>updateField('oldpeak',e.target.value)} required /></Field>
                  <Field label="Slope of peak exercise ST segment"><select value={cardioForm.slope} onChange={(e)=>updateField('slope',e.target.value)} required><option value="">Select</option><option value="1">Upsloping (1)</option><option value="2">Flat (2)</option><option value="3">Downsloping (3)</option></select></Field>
                </FormSection>
                <FormSection number="03" title="Additional dataset features" description="These features are often obtained from clinical tests. If unknown, leave them blank; the model pipeline will impute them.">
                  <Field label="Number of major vessels (ca) — optional"><select value={cardioForm.ca} onChange={(e)=>updateField('ca',e.target.value)}><option value="">Unknown / not provided</option><option value="0">0</option><option value="1">1</option><option value="2">2</option><option value="3">3</option></select></Field>
                  <Field label="Thal test category — optional"><select value={cardioForm.thal} onChange={(e)=>updateField('thal',e.target.value)}><option value="">Unknown / not provided</option><option value="3">Normal (3)</option><option value="6">Fixed defect (6)</option><option value="7">Reversible defect (7)</option></select></Field>
                </FormSection>
                <div className="assessment-note"><strong>Dataset limitation</strong><span>This model was trained on only 303 historical records. Its output is experimental and should not be used to make healthcare decisions.</span></div>
              </>
            )}
            <div className="submit-area">
              <div><strong>{loading ? 'Analyzing your data...' : 'Ready to analyze?'}</strong><p>{loading ? 'Your responses are being processed by the model.' : `Your responses will be processed by the ${title.toLowerCase()} ML model.`}</p></div>
              <button type="submit" className="primary-button submit-button" disabled={loading}>{loading ? 'Analyzing...' : 'Analyze My Risk'} {!loading && <span>→</span>}</button>
            </div>
            {error && <div className="api-error"><strong>Prediction failed</strong><p>{error}</p></div>}
          </form>
        </main>
        <Footer />
      </div>
    )
  }

  return (
    <div className="app">
      <Navbar goHome={goHome} />
      <main>
        <section className="hero-section">
          <div className="hero-content">
            <div className="eyebrow">AI-POWERED HEALTH ASSESSMENT</div>
            <h1>Understand your <span>health through data.</span></h1>
            <p className="hero-description">A machine learning platform that analyzes health indicators to provide an educational model assessment.</p>
            <div className="hero-actions"><button className="primary-button" onClick={() => openAssessment('diabetes')}>Start Diabetes Assessment <span>→</span></button><a href="#models" className="secondary-button">Explore Models</a></div>
          </div>
          <div className="hero-card">
            <div className="card-header"><span>MODEL STATUS</span><span className="live-badge">LIVE</span></div>
            <div className="score-display"><div className="score-circle"><div><strong>ML</strong><span>Powered</span></div></div></div>
            <div className="model-info"><strong>Two specialized models</strong><span>Diabetes + Cardiovascular</span></div>
            <div className="model-stats"><div><strong>82.67%</strong><span>Diabetes ROC-AUC</span></div><div><strong>95.24%</strong><span>Cardio ROC-AUC</span></div><div><strong>2</strong><span>Modules</span></div></div>
          </div>
        </section>
        <section id="models" className="models-section">
          <div className="section-heading"><div><span className="section-label">ASSESSMENT MODULES</span><h2>Choose a health assessment</h2></div><p>Each module uses its own trained machine learning pipeline.</p></div>
          <div className="model-grid">
            <div className="model-card available"><div className="model-card-top"><div className="model-icon">D</div><span className="available-badge">Available</span></div><h3>Diabetes Risk</h3><p>Uses CDC health indicator data to generate an educational diabetes/prediabetes model score.</p><button className="model-button" onClick={() => openAssessment('diabetes')}>Assess Risk <span>→</span></button></div>
            <div className="model-card available"><div className="model-card-top"><div className="model-icon">C</div><span className="available-badge">Available</span></div><h3>Cardiovascular Model Assessment</h3><p>Uses the 13 features of the historical UCI Heart Disease dataset to produce an experimental model score.</p><button className="model-button" onClick={() => openAssessment('cardiovascular')}>Assess Risk <span>→</span></button></div>
          </div>
        </section>
        <section className="method-section"><div className="method-card"><span className="section-label">HOW IT WORKS</span><h2>From health data<br />to ML assessment.</h2><div className="steps"><div className="step"><span>01</span><div><strong>Enter model features</strong><p>Complete the fields required by the selected dataset and model.</p></div></div><div className="step"><span>02</span><div><strong>ML analysis</strong><p>The trained preprocessing and classification pipeline analyzes the inputs.</p></div></div><div className="step"><span>03</span><div><strong>Review the output</strong><p>See a model score, threshold-based label, and input observations.</p></div></div></div></div></section>
      </main>
      <Footer />
    </div>
  )
}

function Navbar({ goHome }) {
  return <nav className="navbar"><button className="brand brand-button" onClick={goHome}><div className="brand-icon">H</div><div><span className="brand-name">HealthML</span><span className="brand-subtitle">Risk Assessment</span></div></button><div className="nav-status"><span className="status-dot" />ML API Online</div></nav>
}

function Footer() {
  return <footer><div><strong>HealthML Risk Assessment</strong><span>Educational machine learning prototype</span></div><p>Not a medical diagnosis. Results are for educational and research purposes only.</p></footer>
}

function FormSection({ number, title, description, children }) {
  return <section className="form-section"><div className="form-section-heading"><span>{number}</span><div><h2>{title}</h2><p>{description}</p></div></div><div className="form-grid">{children}</div></section>
}

function Field({ label, children }) {
  return <label className="form-field"><span>{label}</span>{children}</label>
}

function YesNoField({ label, value, onChange }) {
  return <div className="form-field"><span>{label}</span><div className="choice-group"><button type="button" className={value === '1' ? 'choice active' : 'choice'} onClick={() => onChange('1')}>Yes</button><button type="button" className={value === '0' ? 'choice active' : 'choice'} onClick={() => onChange('0')}>No</button></div><input className="hidden-required" tabIndex="-1" value={value} onChange={() => {}} required aria-hidden="true" /></div>
}

export default App
